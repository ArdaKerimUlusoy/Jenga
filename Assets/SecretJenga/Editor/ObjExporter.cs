using System.Globalization;
using System.IO;
using System.Text;
using UnityEngine;

namespace SecretJenga.EditorTools
{
    /// <summary>Writes a Unity mesh to a Wavefront OBJ file (right-handed, X mirrored, one group per submesh).</summary>
    public static class ObjExporter
    {
        public static void Export(Mesh mesh, string assetPath)
        {
            var ci = CultureInfo.InvariantCulture;
            var sb = new StringBuilder();
            sb.AppendLine("# Secret Jenga - procedurally generated by SecretJengaProjectGenerator");
            sb.AppendLine("o " + mesh.name);
            var v = mesh.vertices;
            var n = mesh.normals;
            var uv = mesh.uv;
            foreach (var p in v) sb.AppendLine(string.Format(ci, "v {0:0.######} {1:0.######} {2:0.######}", -p.x, p.y, p.z));
            foreach (var p in n) sb.AppendLine(string.Format(ci, "vn {0:0.####} {1:0.####} {2:0.####}", -p.x, p.y, p.z));
            bool hasUv = uv != null && uv.Length == v.Length;
            if (hasUv) foreach (var t in uv) sb.AppendLine(string.Format(ci, "vt {0:0.######} {1:0.######}", t.x, t.y));
            for (int s = 0; s < mesh.subMeshCount; s++)
            {
                sb.AppendLine("g " + mesh.name + "_part" + s);
                sb.AppendLine("usemtl material" + s);
                var tris = mesh.GetTriangles(s);
                for (int i = 0; i < tris.Length; i += 3)
                {
                    // mirrored X flips handedness, so reverse winding
                    int a = tris[i] + 1, b = tris[i + 2] + 1, c = tris[i + 1] + 1;
                    sb.AppendLine(hasUv
                        ? $"f {a}/{a}/{a} {b}/{b}/{b} {c}/{c}/{c}"
                        : $"f {a}//{a} {b}//{b} {c}//{c}");
                }
            }
            var full = Path.Combine(Directory.GetCurrentDirectory(), assetPath);
            Directory.CreateDirectory(Path.GetDirectoryName(full));
            File.WriteAllText(full, sb.ToString());
        }
    }
}
